export function ActivityNoConversationSelectedVisual(
  props: EmptyStateVisualBaseProps,
) {
  const reactId = useId();
  const idPrefix = `activity-no-conversation-selected-${reactId.replaceAll(":", "")}`;

  return (
    <EmptyStateSvg viewBox="172 331 1712 1353" {...props}>
      <defs>
        {visiblePaths.map((path) =>
          path.cutoutStart < cutoutPaths.length ? (
            <mask
              key={getMaskId(idPrefix, path.id, path.cutoutStart)}
              id={getMaskId(idPrefix, path.id, path.cutoutStart)}
              x="0"
              y="0"
              width="2048"
              height="2048"
              maskUnits="userSpaceOnUse"
            >
              <rect width="2048" height="2048" fill="white" stroke="none" />
              {cutoutPaths.slice(path.cutoutStart).map((cutoutPath) => (
                <path
                  key={cutoutPath.id}
                  d={cutoutPath.d}
                  fill="black"
                  stroke="none"
                />
              ))}
            </mask>
          ) : null,
        )}
      </defs>

      <g stroke="none">
        {visiblePaths.map((path) => {
          const maskId =
            path.cutoutStart < cutoutPaths.length
              ? getMaskId(idPrefix, path.id, path.cutoutStart)
              : undefined;

          return (
            <path
              key={path.id}
              d={path.d}
              fill={path.fill}
              mask={maskId ? `url(#${maskId})` : undefined}
            />
          );
        })}
      </g>
    </EmptyStateSvg>
  );
}
